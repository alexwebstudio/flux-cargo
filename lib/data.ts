export function rateFor(mode: TariffMode, kg: number) {
  const i = BRACKETS.findIndex((b) => kg >= b.min && kg < b.max);
  return TARIFFS[mode].rates[i === -1 ? 2 : i];
}

export function calcCost(mode: TariffMode, kg: number, goodsK = 1) {
  const billable = Math.max(1, kg); // к оплате минимум 1 кг
  const rate = rateFor(mode, billable);
  return { rate, billable, total: Math.round(billable * rate * goodsK) };
}

